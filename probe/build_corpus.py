"""
Сборка CORPUS.md — дословных цитат из уже записанных логов двух стендов.

Ни одного обращения к модели. Цитаты не набираются руками: они читаются
из jsonl и вставляются как есть, вместе с обрывами, опечатками и
английскими вставками. Комментарий («что показывает», «что было бы
меткой») пишется рядом, а не вместо.

Запуск: .venv/bin/python probe/build_corpus.py > CORPUS.md
"""
from __future__ import annotations

import json
from pathlib import Path

B2B = Path(__file__).resolve().parent.parent
RETAIL = B2B.parent / "retail-lab"


def rows(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def one(path: Path, **match) -> dict:
    for r in rows(path):
        if all(str(r.get(k)) == str(v) for k, v in match.items()):
            return r
    raise KeyError(f"{path}: {match}")


def items(text: str, needle: str) -> list[str]:
    """Пункты перечня, содержащие подстроку. Пункт берётся целиком."""
    out, cur = [], []
    for line in text.split("\n"):
        stripped = line.strip()
        starts = stripped[:3].lstrip().startswith(tuple("0123456789")) and (
            "." in stripped[:4] or ")" in stripped[:4])
        if starts or stripped.startswith(("- ", "* ", "• ")):
            if cur:
                out.append("\n".join(cur).strip())
            cur = [line]
        elif cur:
            cur.append(line)
    if cur:
        out.append("\n".join(cur).strip())
    return [b for b in out if needle in b]


def quote(text: str) -> str:
    """Цитата блоком, чтобы ничего не съела разметка."""
    return "```\n" + text.rstrip() + "\n```"


def card(n, title, src, when, shows, label, text, flag=""):
    print(f"\n### {n}. {title}\n")
    print(f"**Откуда.** {src}\n")
    print(f"**Когда.** {when}\n")
    print("**Дословно:**\n")
    print(quote(text))
    print(f"\n**Что показывает.** {shows}\n")
    print(f"**Что было бы записано меткой.** {label}")
    if flag:
        print(f"\n> {flag}")
    print()


